#!/usr/bin/env python3
"""Haven Desk worker factory — manager-side dispatch + validation.

This is deliberately a manager tool: it creates worker jobs, reads their
results, validates the JSON schema, and writes the accepted volume layer.
It does not author level content itself.

Usage:
  python haven_factory.py status
  python haven_factory.py collect --out "...\\games\\haven-desk\\veil-workers.js"
"""
from __future__ import annotations

import argparse
import json
import re
import urllib.request
from pathlib import Path

FORGE = "http://127.0.0.1:8796"
DEFAULT_OUT = Path(r"<USER>\source\chatagent\games\haven-desk\veil-workers.js")
ANCHOR_RE = re.compile(r"Worker atlas:\s*(\d{4}-\d{2}-\d{2})")


def get(url: str) -> dict:
    req = urllib.request.Request(url, headers={"Accept": "application/json"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read().decode("utf-8"))


def job_state() -> list[dict]:
    return get(FORGE + "/api/dispatcher/state").get("jobs", [])


def extract_array(text: str) -> list | None:
    text = str(text or "").strip()
    if text.startswith("```"):
        text = re.sub(r"^```(?:json)?\s*", "", text)
        text = re.sub(r"\s*```$", "", text)
    start = text.find("[")
    end = text.rfind("]")
    if start < 0 or end <= start:
        return None
    try:
        data = json.loads(text[start:end + 1])
    except Exception:
        return None
    return data if isinstance(data, list) else None


def valid_room(obj) -> dict | None:
    if not isinstance(obj, dict):
        return None
    title = str(obj.get("title") or "").strip()
    question = str(obj.get("question") or "").strip()
    answer = str(obj.get("answer") or "").strip().upper()
    doc = str(obj.get("doc") or "").strip()
    clue = str(obj.get("clue") or "").strip()
    body = obj.get("body")
    if not title or not question or not answer or not doc or not clue:
        return None
    if not re.fullmatch(r"[A-Z0-9][A-Z0-9 _-]{1,23}", answer):
        return None
    if not isinstance(body, list) or len(body) < 1:
        return None
    body = [str(x).strip() for x in body if str(x).strip()]
    if not body:
        return None
    return {
        "title": title[:90],
        "epigraph": str(obj.get("epigraph") or "A recovered stratum.")[:180],
        "body": body[:3],
        "doc": doc[:900],
        "question": question[:300],
        "answer": answer[:24],
        "clue": clue[:300],
    }


def collect(out: Path) -> dict:
    accepted = []
    seen = set()
    source_jobs = []
    for job in job_state():
        if job.get("status") != "returned":
            continue
        m = ANCHOR_RE.search(str(job.get("title") or ""))
        if not m:
            continue
        anchor = m.group(1)
        arr = extract_array(job.get("result") or "")
        if not arr:
            continue
        source_jobs.append(job.get("id"))
        for i, raw in enumerate(arr):
            room = valid_room(raw)
            if not room:
                continue
            key = (anchor, room["title"].lower())
            if key in seen:
                continue
            seen.add(key)
            room["anchor"] = anchor
            room["id"] = "worker:" + anchor + ":" + str(i + 1)
            accepted.append(room)
    payload = "/* Generated by haven_factory.py from validated Forge worker results.\n" \
              "   Do not hand-edit. Each room belongs to an anchor date. */\n" \
              "window.VEIL_WORKER_ROOMS = " + json.dumps(accepted, ensure_ascii=False, indent=2) + ";\n"
    out.write_text(payload, encoding="utf-8")
    return {"ok": True, "accepted": len(accepted), "jobs": source_jobs, "out": str(out)}


def post_job(anchor: str, agent: str, brief: str) -> dict:
    body = {
        "project": "haven-desk",
        "title": "Worker atlas: " + anchor,
        "skill": "forge-worker",
        "agent": agent,
        "auto": True,
        "role": "writer",
        "stage": "production",
        "brief": brief,
    }
    req = urllib.request.Request(
        FORGE + "/api/dispatcher/jobs",
        data=json.dumps(body).encode("utf-8"),
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read().decode("utf-8"))


def retry() -> dict:
    """Re-post failed worker-atlas anchors to free, capable workers."""
    state = get(FORGE + "/api/dispatcher/agents").get("agents", [])
    free = [a for a in state if a.get("status") in ("ready", "standby") and "forge-worker" in (a.get("skills") or [])]
    jobs = [j for j in job_state() if str(j.get("title", "")).startswith("Worker atlas:") and j.get("status") == "failed"]
    posted = []
    for job in jobs:
        if not free:
            break
        anchor = ANCHOR_RE.search(str(job.get("title", "")))
        if not anchor:
            continue
        agent = free.pop(0)["id"]
        try:
            res = post_job(anchor.group(1), agent, str(job.get("brief") or ""))
            posted.append({"anchor": anchor.group(1), "agent": agent, "job": (res.get("job") or {}).get("id")})
        except Exception as exc:
            posted.append({"anchor": anchor.group(1), "agent": agent, "error": str(exc)[:200]})
    return {"ok": True, "posted": posted}


def status() -> dict:
    jobs = [j for j in job_state() if str(j.get("title", "")).startswith("Worker atlas:")]
    return {"jobs": [{"id": j.get("id"), "status": j.get("status"), "agent": j.get("agent"),
                      "title": j.get("title"), "error": (j.get("error") or "")[:160]} for j in jobs]}


def main() -> int:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("status")
    sub.add_parser("retry")
    c = sub.add_parser("collect")
    c.add_argument("--out", default=str(DEFAULT_OUT))
    args = ap.parse_args()
    if args.cmd == "status":
        print(json.dumps(status(), indent=2))
        return 0
    if args.cmd == "retry":
        print(json.dumps(retry(), indent=2))
        return 0
    print(json.dumps(collect(Path(args.out)), indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
