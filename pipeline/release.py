#!/usr/bin/env python3
r"""Build a release package with a verified manifest and rights/credits files.

Usage:
  python release.py --project <PROJECTS>\demo --build <PROJECTS>\demo\build\win \
    --version 0.1.0 --out <PROJECTS>\demo\release

This does not code-sign or upload. It produces a zip, SHA-256 manifest,
BUILD_INFO.json, CREDITS.md and LICENSES.md skeleton. Signing/store metadata
remain explicit operator steps.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import platform
import shutil
import sys
import zipfile
from datetime import datetime, timezone
from pathlib import Path


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def collect(root: Path) -> list[dict]:
    rows = []
    for p in sorted(root.rglob("*")):
        if p.is_file():
            rows.append({"path": str(p.relative_to(root)).replace("\\", "/"), "bytes": p.stat().st_size, "sha256": sha256(p)})
    return rows


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--project", required=True)
    ap.add_argument("--build", required=True)
    ap.add_argument("--version", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--name", default="")
    ap.add_argument("--engine", default="unknown")
    ap.add_argument("--platform", default=platform.system())
    args = ap.parse_args()

    project = Path(args.project).resolve()
    build = Path(args.build).resolve()
    out = Path(args.out).resolve()
    if not build.is_dir():
        print(json.dumps({"ok": False, "error": "build_missing", "build": str(build)}))
        return 2
    if not any(build.iterdir()):
        print(json.dumps({"ok": False, "error": "build_empty", "build": str(build)}))
        return 2

    name = args.name or project.name
    out.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now(timezone.utc).isoformat()
    info = {
        "name": name,
        "version": args.version,
        "engine": args.engine,
        "platform": args.platform,
        "built_from": str(build),
        "packaged_at": stamp,
        "builder": "LYGO Forge release.py",
        "signed": False,
        "signing_note": "No code-signing certificate configured; sign before public distribution.",
    }
    (out / "BUILD_INFO.json").write_text(json.dumps(info, indent=2) + "\n", encoding="utf-8")

    credits = out / "CREDITS.md"
    if not credits.exists():
        credits.write_text(
            f"# {name} — Credits\n\nGenerated by LYGO Forge. Replace with the final team, tools, fonts, music and voice credits.\n\n"
            "## Engine and tools\n\n"
            "- Engine: " + args.engine + "\n"
            "- Production: LYGO Forge\n\n"
            "## Assets\n\n"
            "Every third-party asset must have a source, licence and attribution. Unreviewed assets are not shippable.\n",
            encoding="utf-8",
        )
    licenses = out / "LICENSES.md"
    if not licenses.exists():
        licenses.write_text(
            f"# {name} — Third-party licences\n\nList every dependency, font, sound, model output and code library with its licence text or URL.\n\n"
            "- [ ] Engine licence\n- [ ] Font licences\n- [ ] Music/SFX licences\n- [ ] Voice consent\n- [ ] Model output terms\n- [ ] Code dependency licences\n",
            encoding="utf-8",
        )

    manifest = {"release": info, "files": collect(build), "extra": [{"path": "BUILD_INFO.json", "bytes": (out / "BUILD_INFO.json").stat().st_size}, {"path": "CREDITS.md", "bytes": credits.stat().st_size}, {"path": "LICENSES.md", "bytes": licenses.stat().st_size}]}
    (out / "MANIFEST.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")

    slug = "".join(c if c.isalnum() or c in "-_." else "-" for c in name).strip("-") or "game"
    zip_path = out / f"{slug}-{args.version}-{args.platform.lower()}.zip"
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:
        for p in sorted(build.rglob("*")):
            if p.is_file():
                z.write(p, p.relative_to(build))
        for extra in ("BUILD_INFO.json", "MANIFEST.json", "CREDITS.md", "LICENSES.md"):
            z.write(out / extra, extra)

    result = {
        "ok": True,
        "zip": str(zip_path),
        "bytes": zip_path.stat().st_size,
        "sha256": sha256(zip_path),
        "files": len(manifest["files"]),
        "manifest": str(out / "MANIFEST.json"),
        "signed": False,
        "note": "ZIP is unsigned. Code-sign before public release.",
    }
    (out / "RELEASE.json").write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(result, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
